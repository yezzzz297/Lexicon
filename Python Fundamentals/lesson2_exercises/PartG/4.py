# List: keeps things in order and allows changes.
# Good example: a list of books to read.

# Tuple: keeps things in order and does not allow changes.
# Good example: a fixed place like (x, y).

# Set: stores unique items and does not keep order.
# Good example: checking if a name is in a group.

# Dictionary: stores data in name-value pairs.
# Good example: a product and its stock number.

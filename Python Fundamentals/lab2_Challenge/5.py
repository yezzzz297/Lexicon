# Part 5 - Fixed information

dates = ("10 October", "11 October")
hours = ("09:00", "17:00")
contact = ("Anna", "anna@example.com")

opening, closing = hours

print("First date:", dates[0])
print("Last date:", dates[1])
print("Opens:", opening)
print("Closes:", closing)
print("Contact name:", contact[0])
print("Email:", contact[1])

